    public function run(): void
    {
        $marketing = fn (string $key): ?User => User::query()->where('email', DummyStaffSeeder::email($key))->first();

        if ($marketing('marketing') === null || $marketing('marketing2') === null) {
            $this->call(DummyStaffSeeder::class);
        }

        [$author, $approver] = [$marketing('marketing'), $marketing('marketing2')];

        if (! $author->is_active || ! $approver->is_active) {
            throw new RuntimeException('The dummy Marketing Managers write and approve the sample banners: activate both first.');
        }

        $this->command?->info('Home banners and highlights: '.json_encode($this->seedWith($author, $approver, $author), JSON_UNESCAPED_SLASHES));
    }

    /**
     * Write the banners and highlights as these staff; the approver must be someone other than the author and the publisher.
     *
     * @return array{skipped: bool, images: int, banners: int, highlights: int, left_alone: list<string>}
     */
    public function seedWith(User $author, User $approver, User $publisher): array
    {
        if (app()->isProduction()) {
            throw new RuntimeException('Sample banners and highlights are for local databases only.');
        }

        if (! HomeBanner::isAvailable() || ! HomeHighlight::isAvailable()) {
            return ['skipped' => true, 'images' => 0, 'banners' => 0, 'highlights' => 0, 'left_alone' => []];
        }

        // Allowed for this run even when `.env` refuses sample content for the owner's server (OD-152).
        $sampleContent = config('backoffice.sample_content');
        config(['backoffice.sample_content' => true]);

        try {
            return $this->write(['author' => $author, 'approver' => $approver, 'publisher' => $publisher]);
        } finally {
            config(['backoffice.sample_content' => $sampleContent]);
        }
    }

    /**
     * @param  array{author: User, approver: User, publisher: User}  $staff
     * @return array{skipped: bool, images: int, banners: int, highlights: int, left_alone: list<string>}
     */
    private function write(array $staff): array
    {
        $leftAlone = [];

        // As SampleContentSeeder: content this seeder published and nobody has changed gets a new version only when its
        // words differ; content someone else published, or with a version in progress, is left alone.
        $publish = function (Model $content, array $payload, string $name) use ($staff, &$leftAlone): void {
            $published = $content->publishedRevision;

            if ($content->revisions()->whereIn('state', RevisionState::open())->exists() || ($published !== null && $published->author_id !== $staff['author']->id && (bool) $published->author?->is_active)) {
                $leftAlone[] = $name;

                return;
            }

            if ($published !== null && $published->payload == $content->prepareRevisionPayload($payload, forSubmission: true)) {
                return;
            }

            $draft = app(CreateDraft::class)->handle($content, $staff['author'], $payload);
            app(PublishRevision::class)->handle(app(ApproveRevision::class)->handle(app(SubmitRevision::class)->handle($draft, $staff['author']), $staff['approver']), $staff['publisher']);
        };

        // An item found by words it has had in any version, so one the team has since rewritten is still recognised.
        $find = fn (string $model, string $field, string $value): Model => $model::query()->where($field, $value)->first()
            ?? $model::query()->whereHas('revisions', fn ($revisions) => $revisions->where("payload->{$field}", $value))->first()
            ?? $model::query()->forceCreate(['status' => 'draft']);

        $images = array_map(fn (array $image): MediaAsset => $this->image($image, $staff['author']), self::IMAGES);

        foreach (self::BANNERS as $position => $banner) {
            $links = array_map(fn (array $link): array => ['label' => $link['label'], 'type' => 'section', 'page_id' => null, 'section' => $link['section'], 'product_id' => null, 'url' => null], $banner['links']);

            $publish($find(HomeBanner::class, 'heading', $banner['heading']), [
                'heading' => $banner['heading'],
                'text' => $banner['text'],
                'media_asset_id' => $images[$banner['image']]->getKey(),
                'image_alt' => null,
                'primary_link' => $links[0] ?? null,
                'secondary_link' => $links[1] ?? null,
                'sort_order' => ($position + 1) * 10,
            ], 'HomeBanner "'.$banner['heading'].'"');
        }

        foreach (self::HIGHLIGHTS as $position => $highlight) {
            $publish($find(HomeHighlight::class, 'text', $highlight['text']), [
                'text' => $highlight['text'],
                'icon' => $highlight['icon'],
                'is_sample' => true,
                'sort_order' => ($position + 1) * 10,
            ], 'HomeHighlight "'.$highlight['text'].'"');
        }

        return [
            'skipped' => false,
            'images' => count($images),
            'banners' => count(self::BANNERS),
            'highlights' => count(self::HIGHLIGHTS),
            'left_alone' => $leftAlone,
        ];
    }

    /**
     * The image in the media library, added through the upload action when it is not there yet (found by its title and origin).
     *
     * @param  array{path: string, origin: MediaOrigin, title: string, alt_text: string, licence_type?: string, licence_holder?: string, licence_reference?: string, credit_line?: string, usage_restrictions?: string}  $image
     */
    private function image(array $image, User $uploader): MediaAsset
    {
        $existing = MediaAsset::query()->where('title', $image['title'])->where('origin', $image['origin'])->first();

        if ($existing !== null) {
            return $existing;
        }

        $path = base_path($image['path']);

        if (! is_file($path)) {
            throw new RuntimeException("The banner image {$image['path']} is missing.");
        }

        // The media library moves the file it is given, so it gets a copy: the original stays in the repository.
        $copy = tempnam(sys_get_temp_dir(), 'smartgro-banner-');
        copy($path, $copy);

        try {
            return app(CreateMediaAsset::class)->handle($uploader, new UploadedFile($copy, basename($path), null, null, true), [
                ...collect($image)->except(['path', 'origin'])->all(),
                'origin' => $image['origin']->value,
                'is_decorative' => false,
                'not_from_old_website' => true,
            ]);
        } finally {
            if (is_file($copy)) {
                unlink($copy);
            }
        }
    }
